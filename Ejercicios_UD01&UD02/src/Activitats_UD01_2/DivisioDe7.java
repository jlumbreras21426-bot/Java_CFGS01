package Activitats_UD01_2;

public class DivisioDe7 {

	public static void main(String[] args) {

		// Divisió entre dos enters: divisió entera
		int resultatInt = 7 / 2;
		System.out.println("7 / 2 = " + resultatInt);          // Mostra 3 (es perd el decimal)

		// Divisió amb un decimal: divisió en coma flotant
		double resultatDouble = 7.0 / 2;
		System.out.println("7.0 / 2 = " + resultatDouble);     // Mostra 3.5
		
	}

}
